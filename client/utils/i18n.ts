interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => Promise<void>;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: async () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>('en');

  useEffect(() => {
    const loadLang = async () => {
      try {
        const saved = await AsyncStorage.getItem('appLanguage');
        if (saved && (saved in translations)) {
          setLanguageState(saved as LanguageCode);
        }
      } catch (e) {
        console.log('Error loading saved language:', e);
      }
    };
    loadLang();
  }, []);

  const setLanguage = async (lang: LanguageCode) => {
    try {
      setLanguageState(lang);
      await AsyncStorage.setItem('appLanguage', lang);
    } catch (e) {
      console.log('Error saving language preference:', e);
    }
  };

  const t = (key: string): string => {
    const langDict = translations[language] || translations.en;
    return langDict[key] || translations.en[key] || key;
  };

  return React.createElement(
    LanguageContext.Provider,
    { value: { language, setLanguage, t } },
    children
  );
};

export const useTranslation = () => useContext(LanguageContext);

export const translateValue = (val: any, t: (key: string) => string): string => {
  if (val === null || val === undefined) return '';
  if (typeof val === 'number') return val.toString();
  if (Array.isArray(val)) {
    return val.map((v) => translateValue(v, t)).filter(Boolean).join(', ');
  }
  if (typeof val !== 'string') return String(val);

  const trimmed = val.trim();
  const lower = trimmed.toLowerCase();

  const map: Record<string, string> = {
    'internship': 'internships',
    'scheme': 'schemes',
    'scholarship': 'scholarships',
    'training': 'training',
    'active': 'active',
    'expired': 'expired',
    'closed': 'closed',
    'upcoming': 'upcoming',
    'online': 'online',
    'offline': 'offline',
    'virtual': 'virtual',
    'in-office': 'in_office',
    'work from home': 'work_from_home',
    'hybrid': 'hybrid',
    'unpaid': 'unpaid',
    'paid': 'paid',
    'free': 'free',
    'all states': 'all_states',
    'pan india': 'pan_india',
    'all india': 'pan_india',
    'all': 'all',
    'female': 'female',
    'male': 'male',
    'graduation': 'graduation',
    'post graduation': 'post_graduation',
    'diploma': 'diploma',
    '10th pass': 'pass_10th',
    '12th pass': 'pass_12th',
    '10th': 'pass_10th',
    '12th': 'pass_12th',
    'any stream': 'any_stream',
    'engineering': 'engineering',
    'science': 'science',
    'commerce': 'commerce',
    'arts': 'arts',
    '1st year': 'year_1st',
    '2nd year': 'year_2nd',
    '3rd year': 'year_3rd',
    '4th year': 'year_4th',
    'final year': 'final_year',
    'all years': 'all_years',
  };

  if (map[lower]) {
    const translated = t(map[lower]);
    if (translated && translated !== map[lower]) return translated;
  }

  let result = trimmed;
  result = result.replace(/\bmonths\b/gi, t('months'));
  result = result.replace(/\bmonth\b/gi, t('month'));
  result = result.replace(/\bweeks\b/gi, t('weeks'));
  result = result.replace(/\bweek\b/gi, t('week'));
  result = result.replace(/\byears\b/gi, t('years'));
  result = result.replace(/\byear\b/gi, t('year'));
  result = result.replace(/\bunpaid\b/gi, t('unpaid'));
  result = result.replace(/\bpaid\b/gi, t('paid'));

  return result;
};

